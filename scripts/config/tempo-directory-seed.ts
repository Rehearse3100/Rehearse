function mergeResearchFactPools(
  ...pools: Array<Record<string, FactPoolEntry[]>>
): Record<string, FactPoolEntry[]> {
  const merged: Record<string, FactPoolEntry[]> = {};
  for (const pool of pools) {
    for (const [vertical, entries] of Object.entries(pool)) {
      merged[vertical] = [...(merged[vertical] ?? []), ...entries];
    }
  }
  return merged;
}

